use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    embed_bundled_extensions();
    // App commands are allowed only where a capability grants them (capabilities/*.json), so a
    // window can call exactly the commands it needs and remote pages none.
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(
        tauri_build::AppManifest::new().commands(&[
            "open_input",
            "hibernate",
            "start_info",
            "page_url",
            "focus_page",
            "set_overlay",
            "go_back",
            "open_in_browser",
            "get_settings",
            "save_settings",
            "suspend_shortcut",
            "set_start_at_login",
            "history_list",
            "suggest",
            "history_remove",
            "history_clear",
            "open_settings",
            "preview_theme",
            "set_theme_tokens",
            "extensions_list",
            "reload_extensions",
            "open_extensions_folder",
            "open_extension",
            "site_mode_info",
            "set_site_mode",
            "quit_app",
            "quick_state",
            "quick_command",
            "keymap_info",
            "reveal_download",
            "report_timing",
        ]),
    ))
    .expect("failed to run tauri-build");
}

/// The bundled extensions: every folder in the repository's `extensions/` that has an
/// `extension.json` is embedded into the binary (`$OUT_DIR/bundled_extensions.rs`, included by
/// src/extensions/registry.rs) with include_bytes!. Hidden files, symlinks and tests are left
/// out; the app checks each manifest when it reads them (a test checks they all load).
fn embed_bundled_extensions() {
    let manifest_dir =
        PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets it"));
    let root = manifest_dir.join("..").join("extensions");
    println!("cargo:rerun-if-changed={}", root.display());
    let mut folders: Vec<PathBuf> = fs::read_dir(&root)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .map(|entry| entry.path())
                .filter(|path| is_plain_dir(path) && path.join("extension.json").is_file())
                .collect()
        })
        .unwrap_or_default();
    folders.sort();
    let mut code = String::from(
        "/// Generated by build.rs: the repository's extensions/<id>/ folders.\n\
         pub static BUNDLED: super::Bundled = &[\n",
    );
    for folder in folders {
        let name = folder
            .file_name()
            .and_then(|n| n.to_str())
            .expect("extension folder names are plain text");
        let mut files = Vec::new();
        collect_files(&folder, "", &mut files);
        files.sort();
        writeln!(code, "    ({name:?}, &[").expect("write to a String");
        for (rel, path) in files {
            writeln!(
                code,
                "        ({rel:?}, include_bytes!({:?})),",
                path.display().to_string()
            )
            .expect("write to a String");
        }
        code.push_str("    ]),\n");
    }
    code.push_str("];\n");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets it"));
    fs::write(out.join("bundled_extensions.rs"), code).expect("write bundled_extensions.rs");
}

/// A real directory (not a symlink) whose name doesn't start with a dot.
fn is_plain_dir(path: &Path) -> bool {
    let visible = path
        .file_name()
        .and_then(|n| n.to_str())
        .is_some_and(|n| !n.starts_with('.'));
    visible && fs::symlink_metadata(path).is_ok_and(|m| m.is_dir())
}

/// Every regular file under `dir` as (path relative to the extension with `/`, real path):
/// no hidden files, no symlinks, no test files.
fn collect_files(dir: &Path, prefix: &str, files: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.filter_map(Result::ok) {
        let path = entry.path();
        let Some(name) = path.file_name().and_then(|n| n.to_str()).map(str::to_owned) else {
            continue;
        };
        let Ok(meta) = fs::symlink_metadata(&path) else {
            continue;
        };
        if name.starts_with('.') || name.contains(".test.") {
            continue;
        }
        let rel = format!("{prefix}{name}");
        if meta.is_dir() {
            collect_files(&path, &format!("{rel}/"), files);
        } else if meta.is_file() {
            files.push((rel, path));
        }
    }
}
