//! Which extensions exist: the bundled ones (`extensions/<id>/` in the repository, embedded at
//! build time by build.rs) and, with Developer mode on (settings `developerMode`, off by
//! default), unpacked folders in `<config dir>/extensions/<id>/`. A bad extension is skipped
//! with its reason (logged), never a crash. An unpacked extension can't take a bundled one's id.
//!
//! The registry is read when it is first needed and forgotten when the page window closes, so
//! nothing is held while hibernating and a developer's edits show on the next summon. Bundled
//! files are served from memory; unpacked files are read from disk per request, through
//! paths::on_disk (no symlink out of the folder).

use std::borrow::Cow;
use std::fs;
use std::io::Read;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex, PoisonError};

use tauri::{AppHandle, Runtime};

use super::csp;
use super::manifest::{self, Manifest};
use super::paths::{self, RelPath};
use crate::smoke;
use crate::state;

/// The bundled extensions: `(folder, [(path, bytes)])`, generated by build.rs.
pub type Bundled = &'static [(&'static str, &'static [(&'static str, &'static [u8])])];

mod embedded {
    include!(concat!(env!("OUT_DIR"), "/bundled_extensions.rs"));
}

/// The developer extensions' folder, inside the config folder.
pub const EXTENSIONS_DIR: &str = "extensions";
/// Developer extensions read at most.
pub const MAX_UNPACKED: usize = 64;
/// The largest file an unpacked extension may serve.
pub const MAX_FILE_BYTES: u64 = 16 * 1024 * 1024;
/// The largest icon handed to the toolbar.
pub const MAX_ICON_BYTES: usize = 64 * 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// Shipped with Little Joan.
    Bundled,
    /// An unpacked folder, loaded because Developer mode is on.
    Developer,
}

#[derive(Debug)]
enum Source {
    Bundled(&'static [(&'static str, &'static [u8])]),
    Unpacked(PathBuf),
}

/// One extension that passed every check.
#[derive(Debug)]
pub struct Extension {
    pub manifest: Manifest,
    pub kind: Kind,
    /// Its Content-Security-Policy (csp.rs).
    pub csp: String,
    /// Not switched off in Settings (`disabledExtensions`). A switched-off extension is listed
    /// there, and nothing else sees it: it can't be opened, served or called.
    pub enabled: bool,
    source: Source,
}

impl Extension {
    fn new(manifest: Manifest, kind: Kind, source: Source) -> Extension {
        let csp = csp::policy(&manifest.network_hosts());
        Extension {
            manifest,
            kind,
            csp,
            enabled: true,
            source,
        }
    }

    pub fn id(&self) -> &str {
        &self.manifest.id
    }

    /// The bytes of its file `rel`, or `None` (missing, outside the folder, too big).
    pub fn read(&self, rel: &RelPath) -> Option<Cow<'static, [u8]>> {
        match &self.source {
            Source::Bundled(files) => files
                .iter()
                .find(|(path, _)| *path == rel.as_str())
                .map(|(_, bytes)| Cow::Borrowed(*bytes)),
            Source::Unpacked(root) => {
                let real = paths::on_disk(root, rel).ok()?;
                let mut bytes = Vec::new();
                fs::File::open(real)
                    .ok()?
                    .take(MAX_FILE_BYTES + 1)
                    .read_to_end(&mut bytes)
                    .ok()?;
                (bytes.len() as u64 <= MAX_FILE_BYTES).then_some(Cow::Owned(bytes))
            }
        }
    }

    /// Its icon as a `data:` URI for the toolbar (which can't load `ljext:` files: only the page
    /// webview may), or `None`.
    pub fn icon_data_uri(&self) -> Option<String> {
        let icon = self.manifest.icon.as_ref()?;
        let bytes = self.read(icon)?;
        if bytes.len() > MAX_ICON_BYTES {
            return None;
        }
        let mime = match icon.extension().as_deref() {
            Some("svg") => "image/svg+xml",
            Some("png") => "image/png",
            _ => return None,
        };
        Some(format!("data:{mime};base64,{}", base64(&bytes)))
    }
}

/// An extension that was left out, and why.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Skipped {
    pub name: String,
    pub reason: String,
}

#[derive(Debug, Default)]
pub struct Registry {
    extensions: Vec<Arc<Extension>>,
    pub skipped: Vec<Skipped>,
}

impl Registry {
    /// The extension `id`, if it is there and switched on — what everything but Settings' list
    /// uses.
    pub fn get(&self, id: &str) -> Option<Arc<Extension>> {
        self.find(id).filter(|e| e.enabled)
    }

    /// The extension `id`, switched on or off.
    pub fn find(&self, id: &str) -> Option<Arc<Extension>> {
        self.extensions.iter().find(|e| e.id() == id).cloned()
    }

    /// Every extension that loaded, switched on or off (Settings' list).
    pub fn all(&self) -> &[Arc<Extension>] {
        &self.extensions
    }

    fn add(&mut self, mut extension: Extension, disabled: &[String]) {
        extension.enabled = !disabled.iter().any(|id| id == extension.id());
        self.extensions.push(Arc::new(extension));
    }

    fn skip(&mut self, name: &str, reason: String) {
        self.skipped.push(Skipped {
            name: name.to_owned(),
            reason,
        });
    }
}

/// Reads the extensions: `bundled`, then (when given) the unpacked folders in `unpacked`; the ids
/// in `disabled` are switched off.
pub fn build(bundled: Bundled, unpacked: Option<&Path>, disabled: &[String]) -> Registry {
    let mut registry = Registry::default();
    for (folder, files) in bundled {
        let manifest = files
            .iter()
            .find(|(path, _)| *path == "extension.json")
            .ok_or_else(|| "no extension.json".to_owned())
            .and_then(|(_, bytes)| manifest::parse(bytes));
        let extension = manifest.and_then(|manifest| {
            check(
                &registry,
                folder,
                Extension::new(manifest, Kind::Bundled, Source::Bundled(files)),
            )
        });
        match extension {
            Ok(extension) => registry.add(extension, disabled),
            Err(reason) => registry.skip(folder, reason),
        }
    }
    if let Some(dir) = unpacked {
        read_unpacked(&mut registry, dir, disabled);
    }
    registry
}

/// The folder's name is the id, the id is free, and every file the manifest names is there.
fn check(registry: &Registry, folder: &str, extension: Extension) -> Result<Extension, String> {
    if extension.id() != folder {
        return Err(format!(
            "its folder must be named after its id `{}`",
            extension.id()
        ));
    }
    if registry.find(extension.id()).is_some() {
        return Err(format!("the id `{}` is already taken", extension.id()));
    }
    for file in extension.manifest.named_files() {
        if extension.read(file).is_none() {
            return Err(format!("`{file}` is missing or outside the folder"));
        }
    }
    Ok(extension)
}

fn read_unpacked(registry: &mut Registry, dir: &Path, disabled: &[String]) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let mut folders: Vec<(String, PathBuf)> = entries
        .filter_map(Result::ok)
        .filter(|entry| entry.path().is_dir())
        .map(|entry| {
            (
                entry.file_name().to_string_lossy().into_owned(),
                entry.path(),
            )
        })
        .filter(|(name, _)| !name.starts_with('.'))
        .collect();
    folders.sort();
    for (index, (name, path)) in folders.into_iter().enumerate() {
        if index >= MAX_UNPACKED {
            registry.skip(
                &name,
                format!("only {MAX_UNPACKED} developer extensions are read"),
            );
            continue;
        }
        let manifest = read_manifest(&path).and_then(|bytes| manifest::parse(&bytes));
        let extension = manifest.and_then(|manifest| {
            check(
                registry,
                &name,
                Extension::new(manifest, Kind::Developer, Source::Unpacked(path)),
            )
        });
        match extension {
            Ok(extension) => registry.add(extension, disabled),
            Err(reason) => registry.skip(&name, reason),
        }
    }
}

fn read_manifest(folder: &Path) -> Result<Vec<u8>, String> {
    let rel = paths::clean("extension.json").map_err(|err| err.to_string())?;
    let real = paths::on_disk(folder, &rel).map_err(|err| format!("extension.json: {err}"))?;
    let mut bytes = Vec::new();
    fs::File::open(real)
        .and_then(|file| {
            file.take(manifest::MAX_MANIFEST_BYTES as u64 + 1)
                .read_to_end(&mut bytes)
        })
        .map_err(|err| format!("extension.json: {err}"))?;
    Ok(bytes)
}

/// Standard base64 with padding (RFC 4648), for the icon's data: URI.
fn base64(bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let b = [
            chunk[0],
            chunk.get(1).copied().unwrap_or(0),
            chunk.get(2).copied().unwrap_or(0),
        ];
        let n = (u32::from(b[0]) << 16) | (u32::from(b[1]) << 8) | u32::from(b[2]);
        for (i, shift) in [18u32, 12, 6, 0].into_iter().enumerate() {
            if i <= chunk.len() {
                out.push(char::from(ALPHABET[((n >> shift) & 63) as usize]));
            } else {
                out.push('=');
            }
        }
    }
    out
}

static CACHE: Mutex<Option<Arc<Registry>>> = Mutex::new(None);

/// The registry, read now if it isn't yet (bundled, plus the developer folder while Developer
/// mode is on). Skipped extensions are logged once per read.
pub fn current<R: Runtime>(app: &AppHandle<R>) -> Arc<Registry> {
    let (dir, developer_mode, disabled) = state::with(app, |s| {
        (
            s.data_dir.join(EXTENSIONS_DIR),
            s.settings.developer_mode,
            s.settings.disabled_extensions.clone(),
        )
    });
    let mut cache = CACHE.lock().unwrap_or_else(PoisonError::into_inner);
    if let Some(registry) = cache.as_ref() {
        return Arc::clone(registry);
    }
    let registry = Arc::new(build(
        embedded::BUNDLED,
        developer_mode.then_some(dir.as_path()),
        &disabled,
    ));
    for skipped in &registry.skipped {
        eprintln!(
            "little-joan: skipped the extension {}: {}",
            skipped.name, skipped.reason
        );
        smoke::log(
            "extension-skipped",
            &format!("{} {}", skipped.name, skipped.reason),
        );
    }
    *cache = Some(Arc::clone(&registry));
    registry
}

/// Forgets the registry (the window closed, Settings saved, Reload extensions): the next use
/// reads it again.
pub fn forget() {
    *CACHE.lock().unwrap_or_else(PoisonError::into_inner) = None;
}

