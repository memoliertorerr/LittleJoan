// The default theme as a stylesheet (ui/lib/theme-defaults.css, written by
// scripts/theme-css.mts and checked by a test): the same variables tokens() gives, for the
// system's light and dark, so pages look right before their script applies the user's theme.
import { DEFAULT_THEME, tokens } from "./theme.ts";

function block(selector: string, vars: Record<string, string>, indent: string): string {
  const lines = Object.entries(vars).map(([name, value]) => `${indent}  ${name}: ${value};`);
  return `${indent}${selector} {\n${lines.join("\n")}\n${indent}}`;
}

export function defaultsCss(): string {
  const light = tokens({ ...DEFAULT_THEME, mode: "light" }, false).vars;
  const dark = tokens({ ...DEFAULT_THEME, mode: "dark" }, true).vars;
  return [
    "/* Generated by `node scripts/theme-css.mts` from ui/lib/theme.ts: the default theme's",
    "   variables, light and dark. Don't edit by hand; ui/lib/theme.test.ts checks it. */",
    "",
    block(":root", light, ""),
    "",
    "@media (prefers-color-scheme: dark) {",
    block(":root", dark, "  "),
    "}",
    "",
  ].join("\n");
}
